function addNumbers(firstNumber, secondNumber) {
    return firstNumber + secondNumber;
}

function removeNumbers(firstNumber, secondNumber) {
    return firstNumber - secondNumber;
}

function multiplyNumbers(firstNumber, secondNumber) {
    return firstNumber * secondNumber;
}

let x = 10;
let y = 20;
const result = addNumbers(x,y);
console.log(result);
const result2 = removeNumbers(x,y);
console.log(result2);
const result3 = multiplyNumbers(x,y);
console.log(result3);